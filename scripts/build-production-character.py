"""Run with Blender --background --factory-startup --python this_file -- --mpfb ... --assets ...

Uses licensed MakeHuman anatomical meshes, not geometric body approximations.
No dance or performance animation is generated by this script.
"""
import argparse
import hashlib
import importlib
import json
import subprocess
import sys
from pathlib import Path

import bpy
import addon_utils
from mathutils import Vector

parser = argparse.ArgumentParser()
parser.add_argument("--mpfb", required=True, type=Path)
parser.add_argument("--assets", required=True, type=Path)
args = parser.parse_args(sys.argv[sys.argv.index("--") + 1:])
ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "apps/broadcaster/public/characters/production"
SOURCE = ROOT / "assets/characters/wedding-guest-01"
EVIDENCE = ROOT / "docs/evidence/single-character"
for directory in [OUT, SOURCE, EVIDENCE]:
    directory.mkdir(parents=True, exist_ok=True)

bpy.ops.preferences.extension_repo_add(name="Halay production tools", type="LOCAL",
    use_custom_directory=True, custom_directory=str(args.mpfb.resolve() / "src"))
repo = bpy.context.preferences.extensions.repos[-1]
package = f"bl_ext.{repo.module}.mpfb"
addon_utils.enable(package, default_set=True)
if package not in bpy.context.preferences.addons:
    raise RuntimeError("MPFB could not be enabled")

def service(module, name):
    return getattr(importlib.import_module(f"{package}.services.{module}"), name)

Human = service("humanservice", "HumanService")
Target = service("targetservice", "TargetService")
Export = service("exportservice", "ExportService")
Objects = service("objectservice", "ObjectService")

bpy.ops.object.select_all(action="SELECT")
bpy.ops.object.delete(use_global=False)
authoring = bpy.data.collections.new("AUTHORING - editable MPFB source")
bpy.context.scene.collection.children.link(authoring)
runtime = bpy.data.collections.new("RUNTIME - exported deform rig")
bpy.context.scene.collection.children.link(runtime)

phenotype = Target.get_default_macro_info_dict()
phenotype.update(gender=1.0, age=0.42, muscle=0.48, weight=0.44, height=0.55)
phenotype["race"] = {"caucasian": 0.8, "asian": 0.1, "african": 0.1}
base = Human.create_human(macro_detail_dict=phenotype, scale=0.1, feet_on_ground=True)
base.name = "Guest01.Body.Authoring"
rig = Human.add_builtin_rig(base, "mixamo")
rig.name = "Guest01.Rig.Authoring"

used = []
def asset(relative):
    path = args.assets.resolve() / relative
    if not path.is_file():
        raise FileNotFoundError(path)
    used.append({"path": relative, "sha256": hashlib.sha256(path.read_bytes()).hexdigest()})
    return str(path)

Human.set_character_skin(asset("skins/young_caucasian_male/young_caucasian_male.mhmat"),
    base, skin_type="GAMEENGINE")
for path, kind in [
    ("eyes/high-poly/high-poly.mhclo", "Eyes"),
    ("eyebrows/eyebrow002/eyebrow002.mhclo", "Eyebrows"),
    ("eyelashes/eyelashes01/eyelashes01.mhclo", "Eyelashes"),
    ("teeth/teeth_base/teeth_base.mhclo", "Teeth"),
    ("tongue/tongue01/tongue01.mhclo", "Tongue"),
    ("hair/short02/short02.mhclo", "Hair"),
    ("clothes/male_elegantsuit01/male_elegantsuit01.mhclo", "Clothes"),
    ("clothes/shoes01/shoes01.mhclo", "Clothes"),
]:
    attachment = Human.add_mhclo_asset(asset(path), base, asset_type=kind,
        material_type="GAMEENGINE", subdiv_levels=1)
    if kind == "Eyes":
        # The high-poly eye mesh ships without an assigned iris material.
        eye_material = bpy.data.materials.new("Guest01.BrownEyes")
        eye_material.use_nodes = True
        texture = eye_material.node_tree.nodes.new("ShaderNodeTexImage")
        texture.image = bpy.data.images.load(asset("eyes/materials/brown_eye.png"))
        shader = eye_material.node_tree.nodes.get("Principled BSDF")
        eye_material.node_tree.links.new(texture.outputs["Color"], shader.inputs["Base Color"])
        eye_material.node_tree.links.new(texture.outputs["Alpha"], shader.inputs["Alpha"])
        attachment.data.materials.clear()
        attachment.data.materials.append(eye_material)

source_objects = [rig, *Objects.get_list_of_children(rig)]
for obj in source_objects:
    for collection in list(obj.users_collection):
        collection.objects.unlink(obj)
    authoring.objects.link(obj)
    for modifier in obj.modifiers:
        if modifier.type == "SUBSURF":
            modifier.levels = modifier.render_levels = (0 if any(s in obj.name for s in ["teeth", "tongue", "high-poly", "shoes"]) else 1)

export_rig = Export.create_character_copy(base, name_suffix=".Runtime", place_in_collection=runtime)
export_base = Objects.find_object_of_type_amongst_nearest_relatives(export_rig, "Basemesh")
Export.bake_modifiers_remove_helpers(export_base, bake_masks=True, bake_subdiv=True,
    remove_helpers=True, also_proxy=False)
export_objects = [export_rig, *Objects.get_list_of_children(export_rig)]
for obj in export_objects:
    if obj.type != "MESH":
        continue
    bpy.context.view_layer.objects.active = obj
    # MPFB fits attachments with shape keys. glTF export_morph=False discards
    # active fitting keys unless the mix is baked into the runtime mesh first.
    if obj.data.shape_keys:
        mixed = obj.shape_key_add(name="Baked fitted shape", from_mix=True)
        coordinates = [component for vertex in mixed.data for component in vertex.co]
        obj.shape_key_clear()
        obj.data.vertices.foreach_set("co", coordinates)
        obj.data.update()
    # Body modifiers were baked by ExportService. Bake cloth subdivision on the copy only.
    for modifier in list(obj.modifiers):
        if modifier.type == "SUBSURF" and modifier.levels == 0:
            obj.modifiers.remove(modifier)
        elif modifier.type in {"SUBSURF", "MASK"}:
            bpy.ops.object.modifier_apply(modifier=modifier.name)
    for polygon in obj.data.polygons:
        polygon.use_smooth = True
    for slot in obj.material_slots:
        mat = slot.material
        if not mat or not mat.use_nodes:
            continue
        bsdf = next((n for n in mat.node_tree.nodes if n.type == "BSDF_PRINCIPLED"), None)
        if bsdf:
            bsdf.inputs["Metallic"].default_value = 0
            bsdf.inputs["Roughness"].default_value = 0.8 if "elegantsuit" in obj.name else 0.58
            bsdf.inputs["Specular IOR Level"].default_value = 0.22
            if "high-poly" in obj.name:
                bsdf.inputs["Roughness"].default_value = 0.24
                bsdf.inputs["Specular IOR Level"].default_value = 0.4
            alpha = bsdf.inputs["Alpha"]
            if any(s in obj.name for s in ["short02", "eyebrow", "eyelashes"]):
                if alpha.is_linked:
                    previous = alpha.links[0].from_socket
                    clip = mat.node_tree.nodes.new("ShaderNodeMath")
                    clip.operation = "GREATER_THAN"
                    clip.inputs[1].default_value = 0.4
                    mat.node_tree.links.new(previous, clip.inputs[0])
                    mat.node_tree.links.new(clip.outputs[0], alpha)
            elif "high-poly" not in obj.name:
                for link in list(alpha.links):
                    mat.node_tree.links.remove(link)
                alpha.default_value = 1
            if obj == export_base:
                bsdf.inputs["Subsurface Weight"].default_value = 0.035

# Keep authoring data fully editable, but not superimposed on the runtime instance.
authoring.hide_render = True
authoring.hide_viewport = True
for image in bpy.data.images:
    if image.source == "FILE" and image.size[0] and image.size[1]:
        maximum = max(image.size)
        if maximum > 2048:
            image.scale(round(image.size[0] * 2048 / maximum), round(image.size[1] * 2048 / maximum))
        image.pack()

bpy.context.view_layer.update()
bounds = [obj.matrix_world @ Vector(c) for obj in export_objects if obj.type == "MESH" for c in obj.bound_box]
low, high = min(v.z for v in bounds), max(v.z for v in bounds)
# Keep the native fitted rig at identity scale. Scaling only the armature here
# produces inconsistent glTF inverse binds (visible in Three.js, not Cycles).
height_metres = high - low
export_rig.name = "WeddingGuest01"
export_rig["license"] = "CC0-1.0"
export_rig["dancePerformance"] = "none"
export_rig["artApproval"] = "pending-user-review"

bpy.ops.object.select_all(action="DESELECT")
for obj in export_objects:
    obj.select_set(True)
bpy.context.view_layer.objects.active = export_rig
bpy.ops.export_scene.gltf(filepath=str(OUT / "wedding-guest-01.glb"), export_format="GLB",
    use_selection=True, export_yup=True, export_animations=False, export_extras=True,
    export_skins=True, export_morph=False, export_image_format="AUTO")

# A genuine 3D studio setup saved in the source .blend, not a composited image.
scene = bpy.context.scene
scene.render.engine = "CYCLES"
scene.cycles.samples = 24
scene.cycles.use_denoising = True
scene.render.resolution_x, scene.render.resolution_y = 1080, 1440
scene.render.resolution_percentage = 100
scene.world.color = (0.12, 0.12, 0.12)
scene.view_settings.view_transform = "AgX"
bpy.ops.mesh.primitive_plane_add(size=200)
floor = bpy.context.object
floor.name = "StudioFloor - not exported"
mat = bpy.data.materials.new("Studio charcoal")
mat.diffuse_color = (0.055, 0.065, 0.08, 1)
floor.data.materials.append(mat)
def aim(obj, target):
    obj.rotation_euler = (Vector(target) - obj.location).to_track_quat("-Z", "Y").to_euler()
for name, position, energy, size in [
    ("Key", (3, -4, 4), 500, 3), ("Fill", (-3, -2, 2), 250, 3), ("Rim", (2, 3, 3), 600, 2)]:
    data = bpy.data.lights.new(name, "AREA")
    data.energy, data.shape, data.size = energy, "DISK", size
    light = bpy.data.objects.new(name, data)
    scene.collection.objects.link(light)
    light.location = position
    aim(light, (0, 0, 1))
data = bpy.data.cameras.new("Character inspection camera")
camera = bpy.data.objects.new("Character inspection camera", data)
scene.collection.objects.link(camera)
scene.camera = camera
data.type, data.ortho_scale = "ORTHO", 2.1
camera.location = (0, -4, 0.95)
aim(camera, (0, 0, 0.95))
bpy.ops.wm.save_as_mainfile(filepath=str(SOURCE / "wedding-guest-01.blend"), compress=True)
for name, position in [("blender-front", (0, -4, .95)), ("blender-side", (4, 0, .95))]:
    camera.location = position
    aim(camera, (0, 0, .95))
    scene.render.filepath = str(EVIDENCE / f"{name}.png")
    bpy.ops.render.render(write_still=True)

def yup_bounds(obj):
    points = [obj.matrix_world @ v.co for v in obj.data.vertices]
    points = [(p.x, p.z, -p.y) for p in points]
    return {"min": [min(p[i] for p in points) for i in range(3)],
            "max": [max(p[i] for p in points) for i in range(3)]}

stats = {"blender": bpy.app.version_string, "heightMetres": height_metres,
    "bones": len(export_rig.data.bones), "animationClips": 0, "assets": used,
    "meshes": [{"name": o.name, "vertices": len(o.data.vertices),
        "polygons": len(o.data.polygons), "boundsYUp": yup_bounds(o)} for o in export_objects if o.type == "MESH"],
    "sourceEditable": True, "license": "CC0-1.0", "artApproved": False}
stats["sources"] = {
    "mpfbCommit": subprocess.check_output(["git", "-C", str(args.mpfb.resolve()), "rev-parse", "HEAD"], text=True).strip(),
    "mpfbRepository": "https://github.com/makehumancommunity/mpfb2",
    "systemAssets": "https://files.makehumancommunity.org/asset_packs/makehuman_system_assets/makehuman_system_assets_cc0.zip",
    "systemAssetsSha256": hashlib.sha256((ROOT / ".git/tools/makehuman-system.zip").read_bytes()).hexdigest(),
    "licenseEvidence": "assets/licenses/makehuman-CC0.txt",
}
stats["outputs"] = {}
for path in [OUT / "wedding-guest-01.glb", SOURCE / "wedding-guest-01.blend", Path(__file__).resolve()]:
    stats["outputs"][path.relative_to(ROOT).as_posix()] = {
        "sha256": hashlib.sha256(path.read_bytes()).hexdigest(), "bytes": path.stat().st_size}
(OUT / "build-info.json").write_text(json.dumps(stats, indent=2), encoding="utf-8")
print("CHARACTER_DELIVERY", json.dumps(stats))
